static void draw_solid_rect(float x, float y, float w, float h, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    float x0 = x, y0 = y, x1 = x + w, y1 = y + h;
    GLfloat verts[12] = {
        x0, y0,  x1, y0,  x0, y1,
        x1, y0,  x1, y1,  x0, y1
    };
    glColor4ub(r, g, b, a);
    glVertexPointer(2, GL_FLOAT, 0, verts);
    glDrawArrays(GL_TRIANGLES, 0, 6);
}

static void draw_string(const char *str, float x, float y, float scale, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    if (!str) return;
    float cur_x = x;
    while (*str) {
        char c = *str++;
        if (c < 32 || c > 127) c = '?';
        const uint8_t *glyph = font8x8_basic[c - 32];
        for (int row = 0; row < 8; row++) {
            uint8_t byte = glyph[row];
            for (int col = 0; col < 8; col++) {
                if ((byte >> (7 - col)) & 1) {
                    draw_solid_rect(cur_x + col * scale, y + row * scale, scale, scale, r, g, b, a);
                }
            }
        }
        cur_x += 8.0f * scale;
    }
}

static void render_loading_screen(float progress, int cur_file, int total_est, const char *asset_name, const char *status_msg) {
    if (progress < 0.0f) progress = 0.0f;
    if (progress > 1.0f) progress = 1.0f;

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrthof(0.0f, 960.0f, 544.0f, 0.0f, -1.0f, 1.0f);

    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();

    glDisable(GL_TEXTURE_2D);
    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glEnableClientState(GL_VERTEX_ARRAY);
    glDisableClientState(GL_TEXTURE_COORD_ARRAY);
    glDisableClientState(GL_COLOR_ARRAY);

    // Fondo oscuro temático RPG
    draw_solid_rect(0.0f, 0.0f, 960.0f, 544.0f, 12, 15, 24, 255);

    // Barra de acento superior luminosa
    draw_solid_rect(0.0f, 0.0f, 960.0f, 4.0f, 50, 160, 255, 255);

    // Tarjeta central elegante
    draw_solid_rect(100.0f, 120.0f, 760.0f, 310.0f, 45, 65, 100, 255); // Borde exterior
    draw_solid_rect(102.0f, 122.0f, 756.0f, 306.0f, 18, 23, 36, 255);  // Fondo tarjeta

    // Título y subtítulo en inglés
    draw_string("ZENONIA 4 - VFS ASSET PRELOADER", 130.0f, 145.0f, 2.0f, 240, 245, 255, 255);
    draw_string("Preloading assets to RAM for zero-stutter performance...", 130.0f, 175.0f, 1.4f, 140, 170, 210, 255);

    // Marco de la barra de progreso
    draw_solid_rect(130.0f, 215.0f, 700.0f, 36.0f, 50, 75, 120, 255);
    draw_solid_rect(132.0f, 217.0f, 696.0f, 32.0f, 10, 14, 22, 255);

    // Relleno de la barra de progreso
    float fill_w = 692.0f * progress;
    if (fill_w > 2.0f) {
        draw_solid_rect(134.0f, 219.0f, fill_w, 28.0f, 40, 150, 245, 255);
        draw_solid_rect(134.0f, 219.0f, fill_w, 10.0f, 130, 210, 255, 255); // Resplandor superior
    }

    // Porcentaje y conteo de archivos
    char pct_str[64];
    int pct = (int) (progress * 100.0f);
    if (pct > 100) pct = 100;
    snprintf(pct_str, sizeof(pct_str), "Progress: %d%% (%d / %d files)", pct, cur_file, total_est);
    draw_string(pct_str, 130.0f, 265.0f, 1.5f, 220, 230, 255, 255);

    // Nombre del archivo actual
    char file_str[128];
    if (asset_name && asset_name[0]) {
        snprintf(file_str, sizeof(file_str), "Loading: %s", asset_name);
    } else {
        snprintf(file_str, sizeof(file_str), "Loading: Initializing...");
    }
    draw_string(file_str, 130.0f, 295.0f, 1.3f, 120, 200, 160, 255);

    // Mensaje de estado inferior
    if (status_msg) {
        draw_string(status_msg, 130.0f, 350.0f, 1.4f, 255, 215, 80, 255);
    }

    glMatrixMode(GL_MODELVIEW);
    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();

    vglSwapBuffers(GL_FALSE);
}

static int g_preload_total_est = 600;
static int g_preload_last_ui_update = 0;

static void preload_progress_callback(int cur, const char *name) {
    if (cur > g_preload_total_est) g_preload_total_est = cur + 10;
    float progress = (float) cur / (float) g_preload_total_est;

    if (cur - g_preload_last_ui_update >= 5 || cur == 1) {
        render_loading_screen(progress, cur, g_preload_total_est, name, "PRELOADING GAME ASSETS TO RAM... PLEASE WAIT");
        g_preload_last_ui_update = cur;
    }
}

void zenonia_preloader_run(void) {
    game_log("[Preloader] Starting preloader UI...\n");
    render_loading_screen(0.05f, 0, g_preload_total_est, "assets/", "STARTING VFS ASSET PRELOAD...");

    // Precarga recursiva de assets
    int total_loaded = zenonia_asset_cache_preload_all(preload_progress_callback);

    render_loading_screen(0.95f, total_loaded, total_loaded, "GPU Texture Atlas", "INITIALIZING 8 MEGA-TEXTURE ATLASES IN VRAM...");

#ifdef ZENONIA_GPU_QUADS
    // Inicializar 8 mega-texturas de 1024x1024 en VRAM
    gpu_quads_init(960, 544);
#endif

    // Mensaje de finalización claro
    render_loading_screen(1.0f, total_loaded, total_loaded, "Complete", "PRELOAD FINISHED! STARTING GAME...");
    sceKernelDelayThread(400000); // 0.4s para que el usuario aprecie el 100% completado

    game_log("[Preloader] Preload complete (%d files in RAM, GPU Atlas initialized)\n", total_loaded);
}

static char s_osd_msg[64] = {0};
static int s_osd_timer = 0;

void osd_show_message(const char *msg, int duration_frames) {
    if (msg) {
        strncpy(s_osd_msg, msg, sizeof(s_osd_msg) - 1);
        s_osd_msg[sizeof(s_osd_msg) - 1] = '\0';
        s_osd_timer = duration_frames;
    }
}

void osd_draw(void) {
    if (s_osd_timer <= 0) return;
    s_osd_timer--;

    glViewport(0, 0, 960, 544);

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrthof(0.0f, 960.0f, 544.0f, 0.0f, -1.0f, 1.0f);

    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();

    glDisable(GL_TEXTURE_2D);
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_SCISSOR_TEST);
    glDisable(GL_CULL_FACE);
    glDisable(GL_ALPHA_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glEnableClientState(GL_VERTEX_ARRAY);
    glDisableClientState(GL_TEXTURE_COORD_ARRAY);
    glDisableClientState(GL_COLOR_ARRAY);

    uint8_t alpha = 240;
    if (s_osd_timer < 20) {
        alpha = (uint8_t) ((s_osd_timer * 240) / 20);
    }

    int len = (int) strlen(s_osd_msg);
    float scale = 2.0f;
    float text_w = len * 8.0f * scale;
    float box_w = text_w + 36.0f;
    float box_h = 44.0f;
    float box_x = (960.0f - box_w) / 2.0f;
    float box_y = 22.0f;

    // Caja de fondo oscura translúcida con acento azul brillante
    draw_solid_rect(box_x, box_y, box_w, box_h, 12, 16, 26, alpha);
    draw_solid_rect(box_x, box_y + box_h - 3.0f, box_w, 3.0f, 40, 170, 255, alpha);
    draw_solid_rect(box_x, box_y, box_w, 2.0f, 40, 170, 255, (uint8_t)(alpha * 0.7f));

    // Texto OSD nítido
    draw_string(s_osd_msg, box_x + 18.0f, box_y + 14.0f, scale, 240, 245, 255, alpha);

    glMatrixMode(GL_MODELVIEW);
    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
}
